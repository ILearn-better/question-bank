# -*- coding: utf-8 -*-
"""题型 / 难度 / 置信度 的取值 —— **唯一出处**。

为什么要单独一个文件：
    这三组取值同时被三处消费 ——
      ① 批量识别的提示词（要写进 prompt，让模型只能从里面选）
      ② 后端校验（模型不听话时回落）
      ③ 前端表单（下拉选项）
    以前 ① ② 不存在，只有 ③，所以写在页面里没问题。现在提示词里也要写一份，
    如果两边各写各的，改了题型以后「模型能选的」和「表单能填的」迟早对不上，
    而这种不一致不报错，只会让某几道题的题型存成页面下拉里没有的值。

⚠️ 已知的重复：`frontend/entry.html` 的录题表单里仍有一份自己的拷贝
   （`qtypes` / `difficulties` 两个数组）。那是加这个文件之前的写法，
   本次没动它 —— 改这三组取值时**记得两边一起改**，或把它改成从
   `GET /api/batch/options` 取（新页面 batch.html 就是这么做的）。
"""
from __future__ import annotations

# 题型。顺序即前端下拉的显示顺序。
QTYPES: tuple[str, ...] = (
    "选择题", "填空题", "解答题", "判断题", "证明题", "应用题", "图片题",
)

# 难度。三档，与四套卷种样式的 Section 划分对应（见 services/paper_style.py）。
DIFFICULTIES: tuple[str, ...] = ("基础", "中档", "拔高")

# 模型对「题干转录是否准确」的自评。只用于给审核排队 ——
# 低置信度的排前面，老师先看最可能出错的。
CONFIDENCES: tuple[str, ...] = ("high", "medium", "low")

# 模型给不出合法值时回落成什么。刻意选「最普通」的那个：
# 回落值会被 flags 标出来，老师能看到「这个是被兜底的」。
DEFAULT_QTYPE = "解答题"
DEFAULT_DIFFICULTY = "中档"
DEFAULT_CONFIDENCE = "medium"

# 标签的限制。模型很容易一次吐十个标签，那样标签就没有区分度了。
MAX_TAGS = 4
MAX_TAG_CHARS = 12

# 「这道题是不是依赖图形」的**判据措辞**。
#
# 两个用途，缺一不可：
#   ① 提示词里给模型举例（只说「判断有没有图」它会给得很随意，列出触发词才稳）
#   ② 前端**人工复核**的提示：模型说没图、但题干里出现了这些词 → 黄色提醒请老师确认。
#      这一条是用户点名要的：「ai 有可能判断出现问题，因此最好再加上人工判断逻辑」。
#
# ⚠️ 这里只是「提醒」，不是自动判定。命中不等于有图（「图象」也可能是纯文字描述），
#    没命中也不等于没图（图在题块里但题干一个字都没提）。所以最终以人勾的为准。
FIGURE_KEYWORDS: tuple[str, ...] = (
    "如图", "图象", "图像", "图中", "上图", "下图", "如下图", "如图所",
    "曲线", "阴影", "表格", "示意图", "图形", "描点", "作图", "画图",
)
